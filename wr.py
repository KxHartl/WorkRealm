#!/usr/bin/env python3
"""WorkRealm -- scaffold a work-oriented AI-agent workspace at one of three tiers.

    python wr.py new NAME              task tier (the default, no flag)
    python wr.py new NAME --quick      quick tier: hours to a day
    python wr.py new NAME --project    project tier: weeks to months, KEV-style zones
    python wr.py upgrade --to project  run inside an existing workspace

Tiers are strict extensions: task = quick + more, project = task + more. That is
what makes `upgrade` a pure addition -- nothing has to be moved or renamed.

Standard library only, so it runs on a bare Python 3.10 with no setup.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TIERS_DIR = ROOT / "tiers"
TIERS = ("quick", "task", "project")
DEFAULT_TIER = "task"
VERSION = (ROOT / "VERSION").read_text(encoding="utf-8").strip()

META = ".workrealm.json"
RULES_FRAGMENT = "_RULES.md"  # concatenated into AGENTS.md, never copied
RULES_START = "<!-- workrealm:rules:start -- generated by WorkRealm; `wr upgrade` rewrites this block -->"
RULES_END = "<!-- workrealm:rules:end -->"
TEXT_SUFFIXES = {".md", ".py", ".json", ".txt", ".yaml", ".yml", ".sh", ".ps1", ""}

# Paths under which an existing file may not be modified (new files are allowed).
PROTECTED = {
    "quick": [],
    "task": ["10-research/sources"],
    "project": ["10-research/sources", "40-lab/results", "50-release", "90-archive"],
}
# A remote is cheap insurance for real work and noise for a throwaway.
REMOTE_BY_DEFAULT = {"quick": False, "task": True, "project": True}

CHAT_LANG = {
    "match": "**Chat:** reply in the language the user writes in.",
    "en": "**Chat:** English.",
    "hr": "**Chat:** Croatian.",
}

# Which .ai/policy.py checks run, per tier. Each tier adds; none removes or renames.
CHECKS = {
    "quick": ["secrets", "commit_msg", "english"],
    "task": ["protected_paths", "sources_logged", "naming", "decision_register", "decision_commit_body"],
    "project": ["zone_placement", "adr_format"],
}
# Naming patterns, checked on the first path segment below `under` when a file is added.
DATED = r"\d{4}-\d{2}-\d{2}-[a-z0-9]+(?:-[a-z0-9]+)*(?:\.[a-z0-9]+)*"
NAMING = {
    "quick": [],
    "task": [
        {"under": "10-research/notes", "pattern": DATED, "example": "2026-10-12-vendor-comparison.md"},
    ],
    "project": [
        {"under": "10-research/experiments", "pattern": r"EXP-\d{8}-[a-z0-9]+(?:-[a-z0-9]+)*",
         "example": "EXP-20261012-cache-warmup"},
        {"under": "20-prompts/active", "pattern": DATED, "example": "2026-10-12-restructure.md"},
        {"under": "20-prompts/archive", "pattern": DATED, "example": "2026-10-12-restructure.md"},
        {"under": "30-decisions",
         "pattern": r"ADR-\d{2,}-[a-z0-9]+(?:-[a-z0-9]+)*\.md|ADR-TEMPLATE\.md|DECISIONS\.md"
                    r"|OPEN-ITEMS\.md|CONSTRAINTS\.md|INDEX\.md",
         "example": "ADR-03-storage-backend.md"},
        {"under": "40-lab/results", "pattern": r"RUN-\d{8}(?:-\d{2})?", "example": "RUN-20261012-02"},
        {"under": "50-release", "pattern": r"v\d+\.\d+\.\d+(?:-[\w.]+)?", "example": "v0.2.0-pilot"},
    ],
}
# Tool-owned paths: refreshed by `wr upgrade` so a workspace runs the current checks.
# Everything else is the user's and is never overwritten.
TOOL_OWNED = (".ai/", ".githooks/", ".claude/skills/")
HOOKS_PATH = ".githooks"


def die(msg: str) -> None:
    print(f"wr: {msg}", file=sys.stderr)
    sys.exit(1)


def tiers_upto(tier: str) -> tuple[str, ...]:
    return TIERS[: TIERS.index(tier) + 1]


def render(text: str, ctx: dict[str, str]) -> str:
    for key, value in ctx.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def copy_tier(tier: str, dest: Path, ctx: dict[str, str], overwrite: bool) -> list[str]:
    """Copy one tier's files into dest. Returns the relative paths written."""
    written = []
    src_root = TIERS_DIR / tier
    for src in sorted(src_root.rglob("*")):
        if src.is_dir() or src.name == RULES_FRAGMENT or "__pycache__" in src.parts:
            continue
        rel = src.relative_to(src_root)
        target = dest / rel
        if target.exists() and not overwrite and not rel.as_posix().startswith(TOOL_OWNED):
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix in TEXT_SUFFIXES:
            text = render(src.read_text(encoding="utf-8"), ctx)
            target.write_text(text, encoding="utf-8", newline="\n")
        else:
            shutil.copy2(src, target)
        written.append(rel.as_posix())
    return written


def rules_block(tier: str, ctx: dict[str, str]) -> str:
    parts = [render((TIERS_DIR / t / RULES_FRAGMENT).read_text(encoding="utf-8"), ctx).strip()
             for t in tiers_upto(tier)]
    return f"{RULES_START}\n\n" + "\n\n".join(parts) + f"\n\n{RULES_END}"


def write_agents_md(dest: Path, tier: str, ctx: dict[str, str]) -> None:
    """Rewrite only the generated block; the project-specific section is the user's."""
    path = dest / "AGENTS.md"
    block = rules_block(tier, ctx)
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if RULES_START in text and RULES_END in text:
            head, rest = text.split(RULES_START, 1)
            _, tail = rest.split(RULES_END, 1)
            path.write_text(head + block + tail, encoding="utf-8", newline="\n")
            return
        die("AGENTS.md has no WorkRealm markers; refusing to overwrite it. Add them or move the file.")
    text = (
        f"# {ctx['NAME']} -- rules for AI agents\n\n"
        f"> Tier: **{tier}** · scaffolded by WorkRealm {VERSION}. `CLAUDE.md` imports this file;\n"
        "> rules change HERE, never in a shim.\n\n"
        f"{block}\n\n"
        "## Project-specific rules\n\n"
        "_Rules that apply only to this workspace go here. WorkRealm never touches this section._\n"
    )
    path.write_text(text, encoding="utf-8", newline="\n")


def hook_cmd(script: str) -> dict:
    return {"type": "command", "command": f'python "$CLAUDE_PROJECT_DIR/.ai/hooks/{script}"', "timeout": 20}


STATUS_LINE = {"type": "command", "command": 'python "${CLAUDE_PROJECT_DIR:-.}/.ai/statusline.py"'}
# Secrets are never read into context; tool-owned files are changed only with the user's yes.
PERMISSIONS = {
    "deny": ["Read(./.env)", "Read(./.env.*)", "Read(!.env.example)", "Read(**/*.pem)", "Read(**/*.key)",
             "Read(**/id_rsa*)", "Bash(git push --force *)", "Bash(git push -f *)",
             "PowerShell(git push --force *)", "PowerShell(git push -f *)"],
    "ask": ["Edit(./.ai/**)", "Edit(./.githooks/**)", "Edit(./.workrealm.json)", "Edit(./.claude/settings.json)"],
}


def write_settings(dest: Path, tier: str) -> None:
    """Own `hooks` in .claude/settings.json, add WorkRealm's permission entries and the
    status line (unless the user set their own); leave every other key alone."""
    path = dest / ".claude" / "settings.json"
    settings = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    write_hooks = []
    if tier in ("task", "project"):
        write_hooks.append(hook_cmd("protect_paths.py"))
    if tier == "project":
        write_hooks.append(hook_cmd("zone_guard.py"))
    pre = [{"matcher": "Bash|PowerShell", "hooks": [hook_cmd("bash_guard.py")]}]
    if write_hooks:
        pre.insert(0, {"matcher": "Write|Edit|MultiEdit|NotebookEdit", "hooks": write_hooks})
    settings["hooks"] = {
        "SessionStart": [{"hooks": [hook_cmd("session_start.py")]}],
        "PreToolUse": pre,
        "Stop": [{"hooks": [hook_cmd("checkpoint_gate.py")]}],
    }
    perms = settings.setdefault("permissions", {})
    for kind, rules in PERMISSIONS.items():
        perms[kind] = perms.get(kind, []) + [r for r in rules if r not in perms.get(kind, [])]
    if ".ai/statusline.py" in json.dumps(settings.get("statusLine", ".ai/statusline.py")):
        settings["statusLine"] = STATUS_LINE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8", newline="\n")


def write_meta(dest: Path, meta: dict) -> None:
    (dest / META).write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")


def git(dest: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=dest, capture_output=True, text=True, check=check)


def cumulative(table: dict, tier: str) -> list:
    return [item for t in tiers_upto(tier) for item in table[t]]


def tier_meta(tier: str) -> dict:
    return {"tier": tier, "workrealm_version": VERSION, "protected": PROTECTED[tier],
            "checks": cumulative(CHECKS, tier), "naming": cumulative(NAMING, tier)}


def install_githooks(dest: Path) -> None:
    """Point git at the versioned .githooks/. core.hooksPath is local config, so a fresh
    clone needs `git config core.hooksPath .githooks` once."""
    for hook in (dest / HOOKS_PATH).iterdir():
        hook.chmod(0o755)
    git(dest, "config", "core.hooksPath", HOOKS_PATH)


def create_remote(dest: Path, name: str) -> str:
    if shutil.which("gh") is None:
        return "no remote: `gh` not found. Add one later and every commit will push."
    r = subprocess.run(["gh", "repo", "create", name, "--private", "--source", ".", "--push"],
                       cwd=dest, capture_output=True, text=True)
    if r.returncode != 0:
        return f"no remote: gh repo create failed -- {r.stderr.strip()}"
    return f"remote: private GitHub repo created and pushed ({r.stdout.strip()})"


def cmd_new(args: argparse.Namespace) -> None:
    tier = "quick" if args.quick else "project" if args.project else DEFAULT_TIER
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", args.name):
        die(f"invalid name {args.name!r}: letters, digits, '.', '_', '-' only")
    parent = Path(args.dir).resolve() if args.dir else ROOT.parent
    dest = parent / args.name
    if dest.exists() and any(dest.iterdir()):
        die(f"{dest} exists and is not empty")
    if shutil.which("git") is None:
        die("git not found")

    today = dt.date.today().isoformat()
    ctx = {"NAME": args.name, "DATE": today, "TIER": tier, "CHAT_LANG": CHAT_LANG[args.lang],
           "WR_VERSION": VERSION}
    dest.mkdir(parents=True, exist_ok=True)
    for t in tiers_upto(tier):
        copy_tier(t, dest, ctx, overwrite=True)  # later tiers replace earlier templates
    write_agents_md(dest, tier, ctx)
    write_settings(dest, tier)
    write_meta(dest, {"name": args.name, "created": today, "lang": args.lang, **tier_meta(tier)})

    git(dest, "init", "-b", "main", "-q")
    install_githooks(dest)
    git(dest, "add", "-A")
    git(dest, "commit", "-q", "-m", f"chore: scaffold {tier} workspace from WorkRealm {VERSION}",
        "-m", "Generated structure, rules and hooks; nothing project-specific yet.")

    remote = args.remote if args.remote is not None else REMOTE_BY_DEFAULT[tier]
    status = create_remote(dest, args.name) if remote else "no remote (pass --remote to create one)"
    print(f"Created {tier} workspace: {dest}\n  {status}\n  Next: open it in Claude Code and fill in STATE.md.")


def cmd_upgrade(args: argparse.Namespace) -> None:
    dest = Path(args.path).resolve()
    meta_path = dest / META
    if not meta_path.exists():
        die(f"{dest} is not a WorkRealm workspace (no {META})")
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    current, target = meta["tier"], args.to
    if TIERS.index(target) <= TIERS.index(current):
        die(f"already at {current}; upgrade only goes up ({' -> '.join(TIERS)})")

    ctx = {"NAME": meta["name"], "DATE": dt.date.today().isoformat(), "TIER": target,
           "CHAT_LANG": CHAT_LANG[meta.get("lang", "match")], "WR_VERSION": VERSION}
    added = []
    for t in tiers_upto(target):
        added += copy_tier(t, dest, ctx, overwrite=False)  # never clobber the user's files
    write_agents_md(dest, target, ctx)
    write_settings(dest, target)
    meta.update(tier_meta(target))
    write_meta(dest, meta)
    install_githooks(dest)
    print(f"Upgraded {dest.name}: {current} -> {target}. Wrote {len(added)} file(s):")
    for a in added:
        print(f"  + {a}")
    print("AGENTS.md rules block, .claude/settings.json hooks and tool files (.ai/, .githooks/) refreshed.\n"
          "Review, then commit:\n"
          f'  python .ai/checkpoint.py "chore: upgrade to {target} tier" '
          f'"WorkRealm {VERSION} upgrade: adds the {target}-tier structure, rules and checks."')


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="wr", description=__doc__.split("\n\n")[0])
    p.add_argument("--version", action="version", version=f"WorkRealm {VERSION}")
    sub = p.add_subparsers(dest="cmd", required=True)

    n = sub.add_parser("new", help="create a workspace (task tier unless --quick/--project)")
    n.add_argument("name")
    size = n.add_mutually_exclusive_group()
    size.add_argument("--quick", action="store_true", help="hours to a day: rules, STATE, commit discipline")
    size.add_argument("--project", action="store_true", help="weeks to months: zones, ADRs, lab, releases")
    n.add_argument("--dir", help=f"parent folder (default: {ROOT.parent})")
    n.add_argument("--lang", choices=sorted(CHAT_LANG), default="match", help="chat language rule (default: match)")
    rem = n.add_mutually_exclusive_group()
    rem.add_argument("--remote", dest="remote", action="store_true", default=None,
                     help="create a private GitHub repo (default for task/project)")
    rem.add_argument("--no-remote", dest="remote", action="store_false", help="stay local")
    n.set_defaults(func=cmd_new)

    u = sub.add_parser("upgrade", help="move an existing workspace up a tier, adding files only")
    u.add_argument("--to", choices=TIERS[1:], required=True)
    u.add_argument("--path", default=".", help="workspace root (default: current folder)")
    u.set_defaults(func=cmd_upgrade)

    args = p.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
